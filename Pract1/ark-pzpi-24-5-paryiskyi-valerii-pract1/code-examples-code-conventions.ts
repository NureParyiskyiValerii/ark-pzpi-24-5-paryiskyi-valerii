/**
 * Перетворює дату, отриману від зовнішнього API, у позначку часу.
 *
 * @param raw - рядок дати у форматі ISO без позначки часового поясу
 */
export function parseApiDate(raw: string): number {
  // Зовнішній API повертає дату без позначки часового поясу, тому додаємо Z
  // вручну: інакше середовище виконання тлумачить її як локальний час.
  return Date.parse(`${raw}Z`);
}

/* ========================================================================
 * 5. ПЕРЕВІРКА ДАНИХ НА МЕЖІ ПРОГРАМИ
 * ====================================================================== */

/**
 * Перевіряє, що значення, отримане ззовні, є коректною задачею.
 * Типи стираються під час компіляції, тому дані з мережі перевіряють кодом.
 *
 * @param value - значення невідомого типу (наприклад, результат JSON.parse)
 * @returns true, якщо значення має структуру Task
 */
export function isTask(value: unknown): value is Task {
  if (typeof value !== 'object' || value === null) {
    return false;
  }
  const candidate = value as Record<string, unknown>;
  return (
    typeof candidate.id === 'string' &&
    typeof candidate.title === 'string' &&
    typeof candidate.createdAt === 'number'
  );
}


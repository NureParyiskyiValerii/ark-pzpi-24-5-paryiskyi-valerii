/** Можливі стани задачі. Літеральний тип замість числового коду. */
export type TaskStatus = 'todo' | 'in_progress' | 'done' | 'archived';

/** Задача користувача. */
export interface Task {
  id: string;
  title: string;
  status: TaskStatus;
  createdAt: number;
  doneAt: number | null;
  archivedAt?: Date;
}

/** Помилка: задачу не знайдено у сховищі. */
export class TaskNotFoundError extends Error {
  constructor(message = 'Задачу не знайдено у сховищі') {
    super(message);
    this.name = 'TaskNotFoundError';
  }
}

/* ========================================================================
 * 2. ІМЕНУВАННЯ ТА МАГІЧНІ ЗНАЧЕННЯ
 * ====================================================================== */

/**
 * Кількість мілісекунд в одній добі.
 * Запис через множення показує не лише значення, а й спосіб його отримання.
 */
export const DAY_MS = 24 * 60 * 60 * 1000;

/**
 * Повертає задачі, завершені понад добу тому.
 *
 * @param tasks - перелік задач для перевірки
 * @param now - поточний момент часу в мілісекундах
 * @returns задачі зі станом done, завершені понад добу тому
 */
export function findStaleDone(tasks: Task[], now: number): Task[] {
  return tasks.filter(
    (task) => task.status === 'done' && task.doneAt !== null && now - task.doneAt > DAY_MS,
  );
}

/**
 * Змінює стан задачі та оновлює позначку часу завершення.
 *
 * @param task - задача, стан якої змінюється
 * @param status - новий стан задачі
 * @returns нову задачу зі зміненим станом
 */
export function updateStatus(task: Task, status: TaskStatus): Task {
  const doneAt = status === 'done' ? Date.now() : null;
  return { ...task, status, doneAt };
}

/**
 * Архівує задачу та прибирає її зі списку активних.
 *
 * @param task - задача, яку потрібно архівувати
 * @param now - момент часу для позначки архівування
 * @returns оновлену задачу зі станом archived
 * @throws TaskNotFoundError якщо задачі немає у сховищі
 */
export function archiveTask(task: Task | undefined, now: Date): Task {
  if (!task) {
    throw new TaskNotFoundError();
  }
  return { ...task, status: 'archived', archivedAt: now };
}

